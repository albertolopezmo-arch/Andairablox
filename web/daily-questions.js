function shuffle(items, random) {
  const result = [...items];
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}

export function createDailyRound(random = Math.random, previouslySeen = [], count = 10) {
  const seenTopics=new Set(allQuestions.filter(q=>previouslySeen.includes(q.id)).map(q=>q.topic));
  const seen = new Set(DAILY_QUESTIONS.filter(q=>seenTopics.has(q.topic)).map(q=>q.id));
  let available = DAILY_QUESTIONS.filter(question => !seen.has(question.id));
  const resetHistory = available.length < count;
  if (resetHistory) available = [...DAILY_QUESTIONS];
  const selected = shuffle(available, random).slice(0, Math.min(count, available.length));
  const questions = selected.map(question => {
    const distractors = shuffle(plausibleDistractors(question.prompt,question.answer,question.pool,pools[question.pool]), random).slice(0, 2);
    const options = shuffle([question.answer, ...distractors], random);
    return { ...question, options, correctIndex: options.indexOf(question.answer) };
  });
  return { questions, seenIds: resetHistory ? selected.map(q => q.id) : [...previouslySeen, ...selected.map(q => q.id)], resetHistory };
}
